#!/usr/bin/env python3
"""LAB ONLY (DRF-51): print the kind variant of the real RAGSandbox RGD.

The lab must test the graph that goes to EKS, so this script starts from
gitops/platform/rgd/rag-sandbox.yaml and changes only what kind cannot have.
Every change is listed here and asserted below:

1. no `bucket` node and no `status.bucket` (no Crossplane, no AWS); the app
   gets BUCKET_CHECK=off instead of S3_BUCKET, so /readyz says "bucket": "skipped";
2. SECRET_BACKEND=file with SECRET_DIR=/secrets instead of Secrets Manager:
   the bootstrap Job mounts the platform store (PVC zdr-platform/lab-secrets),
   the app mounts only its tenant's directory, read-only (PVC <tenant>/lab-secrets);
3. DB_SSLMODE=disable: the lab PostgreSQL has no TLS (RDS forces it).

Graph order, readiness, Job name, retry, labels and security settings stay as
in Git. Usage: python labs/p4-kind/lab_rgd.py | kubectl apply -f -
"""
from __future__ import annotations

import copy
import sys
from pathlib import Path

import yaml

SRC = Path(__file__).resolve().parents[2] / "gitops/platform/rgd/rag-sandbox.yaml"


def set_env(container: dict, name: str, value: str | None) -> None:
    env = [e for e in container["env"] if e["name"] != name]
    if value is not None:
        env.append({"name": name, "value": value})
    container["env"] = env


def pod_spec(node: dict) -> dict:
    return node["template"]["spec"]["template"]["spec"]


def main() -> int:
    real = yaml.safe_load(SRC.read_text(encoding="utf-8"))
    lab = copy.deepcopy(real)
    spec = lab["spec"]

    # 1. No bucket.
    spec["resources"] = [r for r in spec["resources"] if r["id"] != "bucket"]
    del spec["schema"]["status"]["bucket"]
    nodes = {r["id"]: r for r in spec["resources"]}
    app = pod_spec(nodes["app"])["containers"][0]
    set_env(app, "S3_BUCKET", None)
    set_env(app, "BUCKET_CHECK", "off")

    # 2 and 3. File store and no TLS, for the Job and the app.
    boot_pod = pod_spec(nodes["bootstrap"])
    app_pod = pod_spec(nodes["app"])
    for c in (boot_pod["containers"][0], app):
        set_env(c, "SECRET_BACKEND", "file")
        set_env(c, "SECRET_DIR", "/secrets")
        set_env(c, "DB_SSLMODE", "disable")
    claim = {"name": "secrets", "persistentVolumeClaim": {"claimName": "lab-secrets"}}
    boot_pod["volumes"] = [claim]
    boot_pod["containers"][0]["volumeMounts"] = [{"name": "secrets", "mountPath": "/secrets"}]
    app_pod["volumes"] = [dict(claim, persistentVolumeClaim={"claimName": "lab-secrets", "readOnly": True})]
    app["volumeMounts"] = [{
        "name": "secrets",
        "mountPath": '${"/secrets/zero-drift/rag/" + schema.metadata.namespace}',
        "readOnly": True,
    }]

    # Guard: nothing references the removed node, and the rest is unchanged.
    text = yaml.safe_dump(lab)
    assert "bucket." not in text and "S3_BUCKET" not in text, "a bucket reference is left"
    real_nodes = {r["id"]: r for r in real["spec"]["resources"]}
    for i in ("platformConfig", "service", "serviceAccount"):
        assert nodes[i] == real_nodes[i], f"{i} must not change"
    for i in ("bootstrap", "app"):
        a, b = copy.deepcopy(nodes[i]), copy.deepcopy(real_nodes[i])
        for n in (a, b):
            p = pod_spec(n)
            p.pop("volumes", None)
            for c in p["containers"]:
                c.pop("env", None)
                c.pop("volumeMounts", None)
        assert a == b, f"{i}: only env and volumes may change"

    print("# GENERATED by labs/p4-kind/lab_rgd.py from gitops/platform/rgd/rag-sandbox.yaml.")
    print("# LAB ONLY: no bucket node, file secret store, no TLS. Do not commit or sync.")
    yaml.safe_dump(lab, sys.stdout, sort_keys=False, width=200)
    return 0


if __name__ == "__main__":
    sys.exit(main())
